// Signature vectors for TendrForwarder: signs fixed `TendrPayment` messages with the real TS signing
// path (ethers `signTypedData` + `forwarderDomain` + `TENDR_PAYMENT_TYPES`) and compares them with
// the fixture the Foundry test `onchain/evm/test/SignatureVectors.t.sol` verifies on-chain. If the
// TS types or domain drift from the committed fixture, this fails; if the fixture drifts from the
// contract, the Foundry test fails.
//
// Regenerate after an intended change: UPDATE_FORWARDER_VECTORS=1 npm test --workspace=@tendr/contracts
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { TypedDataEncoder, Wallet, keccak256, toUtf8Bytes } from 'ethers';
import { describe, expect, it } from 'vitest';
import {
  TENDR_PAYMENT_TYPE,
  TENDR_PAYMENT_TYPES,
  forwarderDomain,
  type TendrPayment,
} from './forwarder.js';

const FIXTURE = fileURLToPath(
  new URL('../../../onchain/evm/test/fixtures/tendr-payment-vectors.json', import.meta.url),
);

// Anvil's well-known first dev key. Test-only; never holds funds.
const TEST_PRIVATE_KEY = '0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80';

interface VectorInput {
  name: string;
  chainId: bigint;
  verifyingContract: string;
  message: Omit<TendrPayment, 'from'>;
}

const INPUTS: VectorInput[] = [
  {
    name: 'base, shopper pays the fee',
    chainId: 8453n,
    verifyingContract: '0x7e7d000000000000000000000000000000000001',
    message: {
      token: '0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913',
      to: '0x1111111111111111111111111111111111111111',
      amount: '100000000',
      fee: '250000',
      feeTo: '0x2222222222222222222222222222222222222222',
      deadline: '1800000600',
      nonce: '0x' + 'a1'.repeat(32),
    },
  },
  {
    name: 'arbitrum, merchant sponsors (no fee)',
    chainId: 42161n,
    verifyingContract: '0x7e7d000000000000000000000000000000000001',
    message: {
      token: '0xaf88d065e77c8cC2239327C5EDb3A432268e5831',
      to: '0x3333333333333333333333333333333333333333',
      amount: '5000000',
      fee: '0',
      feeTo: '0x0000000000000000000000000000000000000000',
      deadline: '1800000900',
      nonce: '0x' + 'b2'.repeat(32),
    },
  },
  {
    name: 'tron mainnet (TIP-712, 20-byte hex addresses)',
    chainId: 728126428n,
    verifyingContract: '0x7e7d000000000000000000000000000000000002',
    message: {
      token: '0xa614f803B6FD780986A42c78Ec9c7f77e6DeD13C',
      to: '0x4444444444444444444444444444444444444444',
      amount: '25000000',
      fee: '1500000',
      feeTo: '0x5555555555555555555555555555555555555555',
      deadline: '1800001200',
      nonce: '0x' + 'c3'.repeat(32),
    },
  },
];

async function buildVectors() {
  const wallet = new Wallet(TEST_PRIVATE_KEY);
  const vectors = [];
  for (const input of INPUTS) {
    const domain = forwarderDomain(input.chainId, input.verifyingContract);
    const message: TendrPayment = { ...input.message, from: wallet.address };
    const signature = await wallet.signTypedData(domain, TENDR_PAYMENT_TYPES, message);
    vectors.push({
      name: input.name,
      chainId: input.chainId.toString(),
      verifyingContract: input.verifyingContract,
      domainSeparator: TypedDataEncoder.hashDomain(domain),
      digest: TypedDataEncoder.hash(domain, TENDR_PAYMENT_TYPES, message),
      message,
      signature,
    });
  }
  return {
    comment:
      'Generated by packages/contracts/src/forwarder-vectors.test.ts (UPDATE_FORWARDER_VECTORS=1); verified by onchain/evm/test/SignatureVectors.t.sol.',
    typehash: keccak256(toUtf8Bytes(TENDR_PAYMENT_TYPE)),
    signer: wallet.address,
    count: vectors.length,
    vectors,
  };
}

describe('TendrForwarder signature vectors', () => {
  it('match the committed fixture the contract verifies', async () => {
    const fresh = await buildVectors();
    if (process.env.UPDATE_FORWARDER_VECTORS === '1') {
      writeFileSync(FIXTURE, JSON.stringify(fresh, null, 2) + '\n');
    }
    const committed: unknown = JSON.parse(readFileSync(FIXTURE, 'utf8'));
    expect(committed).toEqual(fresh);
  });

  it('ethers encodes the same type string the contract hashes', () => {
    // The fixture's `typehash` is checked against TENDR_PAYMENT_TYPEHASH by the Foundry test.
    expect(TypedDataEncoder.from(TENDR_PAYMENT_TYPES).encodeType('TendrPayment')).toBe(
      TENDR_PAYMENT_TYPE,
    );
  });
});
