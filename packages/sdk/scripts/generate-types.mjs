// Maintainer-only: flatten shared schema types into a dependency-free public snapshot.
import ts from 'typescript';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
const sourcePath = fileURLToPath(new URL('../../contracts/src/index.ts', import.meta.url));
const output = new URL('../src/contracts.generated.ts', import.meta.url);
const program = ts.createProgram([sourcePath], {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  strict: true,
  skipLibCheck: true,
});
const checker = program.getTypeChecker();
const source = program.getSourceFile(sourcePath);
const symbols = checker.getExportsOfModule(checker.getSymbolAtLocation(source));
const names = [
  'ErrorCode',
  'SessionStatus',
  'PaymentStatus',
  'RefundReason',
  'HeldReason',
  'SessionExpiredReason',
  'WebhookEventType',
  'FeeMode',
  'GasChain',
  'ExternalTxStatus',
  'SponsorshipMethod',
  'Sponsor',
  'GasReservationState',
  'NetworkFeeView',
  'LineItem',
  'PaymentLinkCreate',
  'PaymentLinkUpdate',
  'LinkSettlementToken',
  'LinkSettlementOptions',
  'ThemeDocument',
  'ThemeCreate',
  'ThemeFromWebsite',
  'ThemeFromStore',
  'ThemePreview',
  'ThemeAssetObject',
  'GasPolicyInput',
  'GasPolicyView',
  'GasUsageView',
];
let text =
  '// Generated by npm run generate:types --workspace=@usetendr/sdk. Do not edit.\n' +
  '// Public types only: no private workspace or schema-library dependency.\n\n';
for (const name of names) {
  const symbol = symbols.find((s) => s.name === name);
  if (!symbol) throw new Error(`Missing contract ${name}`);
  const declaration = symbol.declarations[0];
  if (ts.isInterfaceDeclaration(declaration)) {
    text += declaration.getText() + '\n\n';
  } else {
    const value = checker.typeToString(
      checker.getDeclaredTypeOfSymbol(symbol),
      declaration,
      ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias,
    );
    if (value.includes('import(') || value.includes('z.'))
      throw new Error(`Unresolved type ${name}`);
    text += `export type ${name} = ${value};\n\n`;
  }
}
text = await format(text, { parser: 'typescript', singleQuote: true, printWidth: 100 });
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== text)
    throw new Error('SDK contracts changed: run generate:types');
  console.log('SDK public contract types match the shared schemas.');
} else {
  await writeFile(output, text);
  console.log(`Generated ${names.length} public contract types.`);
}
