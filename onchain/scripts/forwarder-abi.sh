#!/usr/bin/env bash
# Regenerates packages/contracts/src/forwarder-abi.ts from the Foundry build of
# TendrForwarder (onchain/evm/out/TendrForwarder.sol/TendrForwarder.json).
#
# Usage: onchain/scripts/forwarder-abi.sh [--check]
#   --check  fail if the committed ABI differs from a fresh build (CI). It
#            compares the ABI values, not the text, so it needs only node.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TARGET="$ROOT/packages/contracts/src/forwarder-abi.ts"
ARTIFACT="$ROOT/onchain/evm/out/TendrForwarder.sol/TendrForwarder.json"

"$ROOT/onchain/scripts/forge.sh" build --skip test --skip script >/dev/null

if [ "${1:-}" = "--check" ]; then
  node -e '
const fs = require("fs");
const assert = require("assert");
const [artifact, target] = process.argv.slice(1);
const { abi } = JSON.parse(fs.readFileSync(artifact, "utf8"));
const src = fs.readFileSync(target, "utf8");
const body = src.slice(src.indexOf("= [") + 2, src.lastIndexOf("] as const") + 1);
const committed = Function("return " + body)();
try {
  assert.deepStrictEqual(committed, abi);
} catch {
  console.error("forwarder-abi.sh: " + target + " is stale; run onchain/scripts/forwarder-abi.sh");
  process.exit(1);
}
console.log("forwarder-abi.sh: " + target + " is up to date");
' "$ARTIFACT" "$TARGET"
  exit 0
fi

tmp="$(mktemp "${TMPDIR:-/tmp}/forwarder-abi.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
node -e '
const fs = require("fs");
const [artifact, out] = process.argv.slice(1);
const { abi } = JSON.parse(fs.readFileSync(artifact, "utf8"));
const header =
  "// GENERATED by onchain/scripts/forwarder-abi.sh from the Foundry build of\n" +
  "// onchain/evm/src/TendrForwarder.sol. Do not edit by hand.\n";
fs.writeFileSync(
  out,
  header + "export const TENDR_FORWARDER_ABI = " + JSON.stringify(abi, null, 2) + " as const;\n",
);
' "$ARTIFACT" "$tmp"
(cd "$ROOT" && npx --no-install prettier --stdin-filepath "$TARGET" <"$tmp") >"$TARGET"
echo "forwarder-abi.sh: wrote $TARGET"
